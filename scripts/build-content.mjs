import { readFileSync, writeFileSync } from "node:fs";
import { Script } from "node:vm";

// The only source transformation removes function exports from our helper module.
// Each generated classic script initializes those functions in its own closure.
const helpers = readFileSync(new URL("../extension/media-core.js", import.meta.url), "utf8")
  .replace(/^export (?=function )/gm, "");
if (/^\s*(?:import|export)\b/m.test(helpers)) throw new Error("Page helpers must only export function declarations.");
const check = process.argv.includes("--check");
for (const name of ["content", "page-observer"]) {
  const runtime = readFileSync(new URL(`./${name}-runtime.js`, import.meta.url), "utf8");
  const indent = text => text.trimEnd().split("\n").map(line => line ? `  ${line}` : "").join("\n");
  const bundle = `// Generated by scripts/build-content.mjs; edit media-core.js or scripts/${name}-runtime.js.\n` +
    `// Self-contained: this script does not depend on a global helper object.\n(() => {\n${indent(helpers)}\n\n${indent(runtime)}\n})();\n`;
  new Script(bundle, { filename: `${name}.js` });
  const target = new URL(`../extension/${name}.js`, import.meta.url);
  if (check) {
    if (readFileSync(target, "utf8") !== bundle) throw new Error(`${name}.js is stale. Run npm run build.`);
  } else writeFileSync(target, bundle, "utf8");
}
console.log(check ? "Page bundles are current." : "Built self-contained page scripts.");
